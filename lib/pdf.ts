"use client";

import { jsPDF } from "jspdf";

export interface PdfDoc {
  code: string; title: string; description?: string | null; applicant: string; employeeId?: string | null;
  department: string; category: string; recipient?: string | null; recipientOrg?: string | null;
  recipientEmail?: string | null; revision: string; status: string; generatedAt: string;
  remarks?: string | null; company: string;
}

function build(d: PdfDoc) {
  const pdf = new jsPDF({ unit: "mm", format: "a4" });
  const W = pdf.internal.pageSize.getWidth();
  pdf.setFillColor(30, 64, 175);
  pdf.rect(0, 0, W, 28, "F");
  pdf.setTextColor(255).setFont("helvetica", "bold").setFontSize(15);
  pdf.text(d.company.toUpperCase(), 15, 13);
  pdf.setFontSize(10).setFont("helvetica", "normal");
  pdf.text("Document Reference Slip", 15, 20);

  pdf.setTextColor(100).setFontSize(9).text("FINAL UNIQUE CODE", W / 2, 44, { align: "center" });
  pdf.setTextColor(30, 64, 175).setFont("courier", "bold").setFontSize(26);
  pdf.text(d.code, W / 2, 56, { align: "center" });
  pdf.setDrawColor(200).line(15, 63, W - 15, 63);

  const rows: [string, string | null | undefined][] = [
    ["Document Title", d.title], ["Description", d.description], ["Department", d.department],
    ["Category", d.category], ["Revision", d.revision], ["Status", d.status],
    ["Applicant", d.applicant + (d.employeeId ? ` (${d.employeeId})` : "")],
    ["Recipient", [d.recipient, d.recipientOrg].filter(Boolean).join(" - ")],
    ["Recipient Email", d.recipientEmail], ["Generated", d.generatedAt], ["Remarks", d.remarks],
  ];
  let y = 74;
  pdf.setFontSize(10);
  for (const [k, v] of rows) {
    if (!v) continue;
    pdf.setFont("helvetica", "bold").setTextColor(80).text(k, 15, y);
    pdf.setFont("helvetica", "normal").setTextColor(20);
    const lines = pdf.splitTextToSize(v, W - 80);
    pdf.text(lines, 60, y);
    y += Math.max(8, lines.length * 5 + 3);
  }
  pdf.setFontSize(8).setTextColor(130).text("Generated by the Unique Numbering Portal. This reference is system-issued and cannot be edited.", 15, 285);
  return pdf;
}

export function downloadPdf(d: PdfDoc) {
  build(d).save(`${d.code}.pdf`);
}

export function printPdf(d: PdfDoc) {
  const pdf = build(d);
  pdf.autoPrint();
  const url = URL.createObjectURL(pdf.output("blob"));
  window.open(url, "_blank");
}
